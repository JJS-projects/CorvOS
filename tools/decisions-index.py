#!/usr/bin/env python3
"""Write docs/decisions-index.md: one line per decision in docs/decisions.md.

    tools/decisions-index.py          rewrite the index
    tools/decisions-index.py --check  fail if the index is out of date (run by `make test`)

decisions.md is append-only; this index is generated from it, never edited by hand.
Each line is the number, the title and the start of the choice (the first sentence,
cut at 100 characters). Read the full entry in decisions.md when it matters.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = os.path.join(ROOT, "docs", "decisions.md")
INDEX = os.path.join(ROOT, "docs", "decisions-index.md")
WIDTH = 100

HEADER = """# Decision index

One line per entry of [decisions.md](decisions.md): number, title, start of the
choice. Generated by `tools/decisions-index.py` (do not edit; `make test` checks it
is current). Open the full entry for the alternatives and the principle that settled it.

"""


def build():
    lines = []
    for row in open(SOURCE).read().splitlines():
        m = re.match(r"\| (\d+)\s+\| (.*?)\s+\| (.*?)\s+\| .*", row)
        if not m:
            continue
        number, title, choice = m.groups()
        choice = re.sub(r"[`*]", "", choice)
        first = re.split(r"(?<=[.])\s", choice, maxsplit=1)[0]
        if len(first) > WIDTH:
            first = first[:WIDTH].rsplit(" ", 1)[0] + "…"
        lines.append(f"- {number} {title}: {first}")
    return HEADER + "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        if not os.path.exists(INDEX) or open(INDEX).read() != text:
            sys.exit("docs/decisions-index.md is out of date: run tools/decisions-index.py")
    else:
        open(INDEX, "w").write(text)
