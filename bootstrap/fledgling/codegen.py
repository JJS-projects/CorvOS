"""Code generator: checked syntax tree -> GNU AArch64 assembly text.

Deliberately simple, since Fledgling is thrown away after milestone 5:
  - every expression is computed into x0; temporaries are pushed on the stack
  - every local and parameter lives in an 8-byte stack slot below x29
  - x16 and x17 are scratch registers (AAPCS64 IP0/IP1)

Values are kept in 64-bit registers in normal form: unsigned types
zero-extended, signed types sign-extended, bool as 0 or 1. Every operation
restores normal form, which keeps comparisons simple.

Integer overflow, division by zero and oversized shifts branch to a panic stub
that calls the kernel's `rook_panic(message, file, line)`, which never returns.

Functions follow AAPCS64 (arguments in x0-x7, result in x0), so Rook and
assembly can call each other.
"""

import os

from . import syntax as S
from .rtypes import BOOL, UNIT, is_int

PANIC_MESSAGES = {
    "overflow": "integer overflow",
    "div0": "division by zero",
    "shift": "shift amount too large",
}

SIGNED_COND = {"<": "lt", "<=": "le", ">": "gt", ">=": "ge"}
UNSIGNED_COND = {"<": "lo", "<=": "ls", ">": "hi", ">=": "hs"}
EQ_COND = {"==": "eq", "!=": "ne"}
SIGN_EXTEND = {8: "sxtb", 16: "sxth", 32: "sxtw"}
MASK64 = (1 << 64) - 1


def generate(program, filename):
    return Gen(os.path.basename(filename)).program(program)


class Gen:
    def __init__(self, filename):
        self.filename = filename
        self.lines = []
        self.labels = 0

    def emit(self, text):
        self.lines.append("    " + text)

    def label(self, name):
        self.lines.append(f"{name}:")

    def new_label(self, hint):
        self.labels += 1
        return f".L{hint}_{self.labels}"

    # ---- top level -----------------------------------------------------

    def program(self, prog):
        self.lines.append(f"// Generated by Fledgling from {self.filename}. Do not edit.")
        self.lines.append("    .text")
        for item in prog.items:
            if isinstance(item, S.FnDecl) and item.body is not None:
                self.function(item)
        self.lines.append("")
        self.lines.append("    .section .rodata")
        for key, text in PANIC_MESSAGES.items():
            self.lines.append(f".Lmsg_{key}: .asciz \"{text}\"")
        self.lines.append(f".Lfile: .asciz \"{self.filename}\"")
        return "\n".join(self.lines) + "\n"

    def function(self, fn):
        self.fn = fn
        self.ret_label = self.new_label(f"ret_{fn.name}")
        self.panics = []        # (label, kind, line)
        self.loops = []         # (continue_label, break_label)

        self.lines.append("")
        self.lines.append(f"// fn {fn.name} (line {fn.pos.line})")
        self.emit(f".global {fn.name}")
        self.emit(".balign 4")
        self.label(fn.name)
        self.emit("stp x29, x30, [sp, #-16]!")
        self.emit("mov x29, sp")
        frame = (8 * fn.nslots + 15) // 16 * 16
        if frame:
            if frame <= 4095:
                self.emit(f"sub sp, sp, #{frame}")
            else:
                self.emit(f"ldr x16, ={frame}")
                self.emit("sub sp, sp, x16")
        # Parameters: normalise (the caller may be assembly) and store.
        for i, param in enumerate(fn.params):
            self.emit(f"mov x0, x{i}")
            self.normalize(param.ty)
            self.store_slot(param.slot)

        self.block(fn.body)

        self.label(self.ret_label)
        self.emit("mov sp, x29")
        self.emit("ldp x29, x30, [sp], #16")
        self.emit("ret")

        for label, kind, line in self.panics:
            self.label(label)
            self.emit(f"adr x0, .Lmsg_{kind}")
            self.emit("adr x1, .Lfile")
            self.emit(f"ldr x2, ={line}")
            self.emit("bl rook_panic")

    # ---- helpers -------------------------------------------------------

    def slot_operand(self, slot):
        offset = 8 * (slot + 1)
        if offset <= 256:
            return f"[x29, #-{offset}]"
        self.emit(f"ldr x17, ={offset}")
        self.emit("sub x17, x29, x17")
        return "[x17]"

    def load_slot(self, slot, reg="x0"):
        self.emit(f"ldr {reg}, {self.slot_operand(slot)}")

    def store_slot(self, slot):
        self.emit(f"str x0, {self.slot_operand(slot)}")

    def push(self):
        self.emit("str x0, [sp, #-16]!")

    def pop(self, reg):
        self.emit(f"ldr {reg}, [sp], #16")

    def load_imm(self, value, reg="x0"):
        value &= MASK64
        if value < 65536:
            self.emit(f"mov {reg}, #{value}")
        else:
            self.emit(f"ldr {reg}, ={value:#x}")

    def panic_branch(self, cond, kind, pos):
        """Emit a branch to a new panic stub. `cond` is e.g. "b.cs", "cbnz x16"."""
        label = self.new_label(f"panic_{kind}")
        self.panics.append((label, kind, pos.line))
        self.emit(f"{cond}, {label}" if cond.startswith("cb") else f"{cond} {label}")

    def normalize(self, ty):
        """Bring x0 into normal form for `ty` (used after casts and calls)."""
        if ty == BOOL:
            self.emit("tst w0, #0xff")
            self.emit("cset x0, ne")
        elif is_int(ty) and ty.bits < 64:
            if ty.signed:
                self.emit(f"{SIGN_EXTEND[ty.bits]} x0, w0")
            elif ty.bits == 32:
                self.emit("mov w0, w0")
            else:
                self.emit(f"and x0, x0, #{(1 << ty.bits) - 1:#x}")

    def check_fits(self, ty, pos):
        """x0 holds an exact result (no 64-bit overflow happened); panic if it
        doesn't fit in `ty` (bits < 64)."""
        if ty.signed:
            self.emit(f"{SIGN_EXTEND[ty.bits]} x16, w0")
            self.emit("cmp x16, x0")
            self.panic_branch("b.ne", "overflow", pos)
        else:
            self.emit(f"lsr x16, x0, #{ty.bits}")
            self.panic_branch("cbnz x16", "overflow", pos)

    # ---- statements ----------------------------------------------------

    def block(self, block):
        for stmt in block.stmts:
            self.stmt(stmt)

    def stmt(self, s):
        self.lines.append(f"    // line {s.pos.line}")
        if isinstance(s, S.Decl):
            self.expr(s.init)
            self.store_slot(s.slot)
        elif isinstance(s, S.Assign):
            self.expr(s.value)
            self.store_slot(s.target.slot)
        elif isinstance(s, S.ExprStmt):
            self.expr(s.expr)
        elif isinstance(s, S.If):
            else_label = self.new_label("else")
            end_label = self.new_label("endif")
            self.expr(s.cond)
            self.emit(f"cbz x0, {else_label}")
            self.block(s.then)
            self.emit(f"b {end_label}")
            self.label(else_label)
            if isinstance(s.else_, S.If):
                self.stmt(s.else_)
            elif isinstance(s.else_, S.Block):
                self.block(s.else_)
            self.label(end_label)
        elif isinstance(s, S.Loop):
            start = self.new_label("loop")
            end = self.new_label("endloop")
            self.label(start)
            if s.cond is not None:
                self.expr(s.cond)
                self.emit(f"cbz x0, {end}")
            self.loops.append((start, end))
            self.block(s.body)
            self.loops.pop()
            self.emit(f"b {start}")
            self.label(end)
        elif isinstance(s, S.ForRange):
            # The end is evaluated once. The variable can't overflow when
            # incremented, because it is always below the end.
            cond = self.new_label("range")
            step = self.new_label("rangestep")
            end = self.new_label("endrange")
            self.expr(s.start)
            self.store_slot(s.slot)
            self.expr(s.end)
            self.store_slot(s.end_slot)
            self.label(cond)
            self.load_slot(s.slot)
            self.load_slot(s.end_slot, "x1")
            self.emit("cmp x0, x1")
            self.emit(f"{'b.ge' if s.ty.signed else 'b.hs'} {end}")
            self.loops.append((step, end))
            self.block(s.body)
            self.loops.pop()
            self.label(step)
            self.load_slot(s.slot)
            self.emit("add x0, x0, #1")
            self.store_slot(s.slot)
            self.emit(f"b {cond}")
            self.label(end)
        elif isinstance(s, S.Break):
            self.emit(f"b {self.loops[-1][1]}")
        elif isinstance(s, S.Continue):
            self.emit(f"b {self.loops[-1][0]}")
        elif isinstance(s, S.Return):
            if s.value is not None:
                self.expr(s.value)
            self.emit(f"b {self.ret_label}")
        else:
            raise AssertionError(f"unknown statement {s!r}")

    # ---- expressions ---------------------------------------------------

    def expr(self, e):
        if isinstance(e, S.IntLit):
            self.load_imm(e.value)
        elif isinstance(e, S.BoolLit):
            self.emit(f"mov x0, #{int(e.value)}")
        elif isinstance(e, S.Name):
            if e.const_value is not None:
                self.load_imm(e.const_value)
            else:
                self.load_slot(e.slot)
        elif isinstance(e, S.Unary):
            self.unary(e)
        elif isinstance(e, S.Binary):
            self.binary(e)
        elif isinstance(e, S.Cast):
            self.expr(e.expr)
            self.normalize(e.ty)
        elif isinstance(e, S.IfExpr):
            else_label = self.new_label("ifelse")
            end_label = self.new_label("ifend")
            self.expr(e.cond)
            self.emit(f"cbz x0, {else_label}")
            self.expr(e.then)
            self.emit(f"b {end_label}")
            self.label(else_label)
            self.expr(e.else_)
            self.label(end_label)
        elif isinstance(e, S.Call):
            for arg in e.args:
                self.expr(arg)
                self.push()
            for i in reversed(range(len(e.args))):
                self.pop(f"x{i}")
            self.emit(f"bl {e.callee}")
            if e.ty != UNIT:
                self.normalize(e.ty)
        else:
            raise AssertionError(f"unknown expression {e!r}")

    def unary(self, e):
        self.expr(e.operand)
        ty = e.ty
        if e.op == "-":
            if ty.bits == 64:
                self.emit("negs x0, x0")
                self.panic_branch("b.vs", "overflow", e.pos)
            else:
                self.emit("neg x0, x0")
                self.check_fits(ty, e.pos)
        elif ty == BOOL:
            self.emit("eor x0, x0, #1")
        else:
            self.emit("mvn x0, x0")
            self.normalize(ty)

    def binary(self, e):
        op = e.op
        if op in ("and", "or") and e.ty == BOOL:
            # Logical, short-circuit: x0 is already the answer if the left
            # side decides it.
            end = self.new_label("logic")
            self.expr(e.left)
            self.emit(f"{'cbz' if op == 'and' else 'cbnz'} x0, {end}")
            self.expr(e.right)
            self.label(end)
            return

        self.expr(e.left)
        self.push()
        self.expr(e.right)
        self.emit("mov x1, x0")
        self.pop("x0")
        operand = e.left.ty

        if op in EQ_COND or op in SIGNED_COND:
            if op in EQ_COND:
                cond = EQ_COND[op]
            else:
                cond = (SIGNED_COND if operand.signed else UNSIGNED_COND)[op]
            self.emit("cmp x0, x1")
            self.emit(f"cset x0, {cond}")
            return

        ty = e.ty
        if op == "+":
            self.add_sub("adds" if ty.bits == 64 else "add", ty, e)
        elif op == "-":
            if not ty.signed:
                self.emit("subs x0, x0, x1")
                self.panic_branch("b.lo", "overflow", e.pos)
            else:
                self.add_sub("subs" if ty.bits == 64 else "sub", ty, e)
        elif op == "*":
            if ty.bits == 64:
                self.emit(f"{'smulh' if ty.signed else 'umulh'} x16, x0, x1")
                self.emit("mul x0, x0, x1")
                if ty.signed:
                    self.emit("cmp x16, x0, asr #63")
                    self.panic_branch("b.ne", "overflow", e.pos)
                else:
                    self.panic_branch("cbnz x16", "overflow", e.pos)
            else:
                self.emit("mul x0, x0, x1")     # exact: both fit in 32 bits
                self.check_fits(ty, e.pos)
        elif op in ("/", "%"):
            self.panic_branch("cbz x1", "div0", e.pos)
            div = "sdiv" if ty.signed else "udiv"
            if op == "/":
                if ty.signed and ty.bits == 64:
                    # MIN / -1 overflows; the hardware wouldn't trap.
                    ok = self.new_label("divok")
                    self.emit("cmn x1, #1")
                    self.emit(f"b.ne {ok}")
                    self.emit("mov x16, #0x8000000000000000")
                    self.emit("cmp x0, x16")
                    self.panic_branch("b.eq", "overflow", e.pos)
                    self.label(ok)
                self.emit(f"{div} x0, x0, x1")
                if ty.signed and ty.bits < 64:
                    self.check_fits(ty, e.pos)
            else:
                self.emit(f"{div} x16, x0, x1")
                self.emit("msub x0, x16, x1, x0")
        elif op in ("and", "or", "xor"):
            # Bitwise on integers (and `xor` on bools): normal form is kept.
            insn = {"and": "and", "or": "orr", "xor": "eor"}[op]
            self.emit(f"{insn} x0, x0, x1")
        elif op in ("shl", "shr"):
            # Negative amounts are huge when compared unsigned, so this
            # catches them too.
            self.emit(f"cmp x1, #{ty.bits}")
            self.panic_branch("b.hs", "shift", e.pos)
            if op == "shl":
                self.emit("lsl x0, x0, x1")
                self.normalize(ty)
            else:
                self.emit(f"{'asr' if ty.signed else 'lsr'} x0, x0, x1")
        else:
            raise AssertionError(f"unknown operator {op}")

    def add_sub(self, insn, ty, e):
        self.emit(f"{insn} x0, x0, x1")
        if ty.bits == 64:
            # adds: unsigned overflow sets carry; signed sets V.
            self.panic_branch("b.vs" if ty.signed else "b.cs", "overflow", e.pos)
        else:
            self.check_fits(ty, e.pos)

