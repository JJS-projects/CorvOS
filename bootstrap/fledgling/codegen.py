"""Code generator: checked syntax tree -> GNU AArch64 assembly text.

Deliberately simple, since Fledgling is thrown away after milestone 5:
  - every expression is computed into x0; temporaries are pushed on the stack
  - every local and parameter lives in an 8-byte stack slot below x29
  - x16 and x17 are scratch registers (AAPCS64 IP0/IP1)

Values are kept in 64-bit registers in normal form: unsigned types
zero-extended, signed types sign-extended, bool as 0 or 1. Every operation
restores normal form, which keeps comparisons simple.

Integer overflow, division by zero and oversized shifts branch to a panic stub
that calls the kernel's `rook_panic(message, message_length, file, file_length,
line)`, which never returns. `panic("...")` calls it too.

Text in quotes becomes a `Bytes` value in read-only data: two words, the
address of the bytes and their length.

Functions follow AAPCS64 (arguments in x0-x7, result in x0), so Rook and
assembly can call each other.

Structs and enums live in memory, never in registers. Such an expression
evaluates to the *address* of its value. Each value takes one 8-byte word per
scalar field, nested values inline. An enum value is a tag word (the variant's
index) followed by the variant's fields, padded with zeros to the size of the
largest variant. Arguments are passed as addresses (they are lent), a result
is written to the address the caller passes in x8 (AAPCS64's indirect result
register), and a method receives the address of its value in x0, ahead of its
other arguments.

`self.depth` counts the temporaries pushed on the stack. A `break` or
`continue` inside a `match` used as a value (say, as a call argument) pops the
ones pushed since its loop began.
"""

import os

from . import syntax as S
from .rtypes import BOOL, UNIT, is_aggregate, is_enum, is_int, words

PANIC_MESSAGES = {
    "overflow": "integer overflow",
    "div0": "division by zero",
    "shift": "shift amount too large",
    "shiftlost": "shl lost set bits",
}

SIGNED_COND = {"<": "lt", "<=": "le", ">": "gt", ">=": "ge"}
UNSIGNED_COND = {"<": "lo", "<=": "ls", ">": "hi", ">=": "hs"}
EQ_COND = {"==": "eq", "!=": "ne"}
SIGN_EXTEND = {8: "sxtb", 16: "sxth", 32: "sxtw"}
MASK64 = (1 << 64) - 1


LOAD_INSNS = {"load8": "ldrb w0", "load16": "ldrh w0", "load32": "ldr w0", "load64": "ldr x0"}
STORE_INSNS = {"store8": "strb w1", "store16": "strh w1", "store32": "str w1",
               "store64": "str x1"}


def generate(program):
    return Gen().program(program)


class Gen:
    def __init__(self):
        self.lines = []
        self.labels = 0
        self.files = {}         # source path -> label of its name, for panics
        self.strings = {}       # bytes -> label of the Bytes value

    def emit(self, text):
        self.lines.append("    " + text)

    def label(self, name):
        self.lines.append(f"{name}:")

    def new_label(self, hint):
        self.labels += 1
        return f".L{hint}_{self.labels}"

    # ---- top level -----------------------------------------------------

    def program(self, prog):
        names = sorted({os.path.basename(item.file or "<input>") for item in prog.items})
        self.lines.append(f"// Generated by Fledgling from {', '.join(names)}. Do not edit.")
        self.lines.append("    .text")
        for item in prog.items:
            if isinstance(item, S.FnDecl) and item.body is not None:
                self.function(item)
            elif isinstance(item, (S.StructDecl, S.EnumDecl)):
                for method in item.methods:
                    self.function(method)
            elif isinstance(item, S.ActorDecl):
                if item.new is not None:
                    self.function(item.new)
                for handler in item.handlers:
                    self.function(handler)
                self.dispatcher(item)
        self.lines.append("")
        self.lines.append("    .section .rodata")
        for key, text in PANIC_MESSAGES.items():
            self.lines.append(f".Lmsg_{key}: .ascii \"{text}\"")
        for path, label in self.files.items():
            self.lines.append(f"{label}: .ascii \"{os.path.basename(path)}\"")
        for data, label in self.strings.items():
            # A Bytes value (address, length), then the bytes themselves.
            self.lines.append("    .balign 8")
            self.lines.append(f"{label}: .quad {label}_data, {len(data)}")
            if data:
                self.lines.append(f"{label}_data: .byte {', '.join(str(b) for b in data)}")
            else:
                self.lines.append(f"{label}_data:")
        return "\n".join(self.lines) + "\n"

    def dispatcher(self, actor):
        """`Name__dispatch(self, handler, a0, a1, a2, a3)`: Raven's scheduler calls
        this with a message taken from the mailbox. It jumps to the handler
        whose number the message carries, moving the arguments down one register
        so the handler sees `self` in x0 and its arguments from x1."""
        symbol = f"{actor.name}__dispatch"
        self.lines.append("")
        self.lines.append(f"// dispatcher for actor {actor.name} (line {actor.pos.line})")
        self.emit(f".global {symbol}")
        self.emit(".balign 4")
        self.label(symbol)
        for handler in actor.handlers:
            number = handler.number
            skip = self.new_label("handler")
            self.emit(f"cmp x1, #{number}")
            self.emit(f"b.ne {skip}")
            for i in range(1, 5):
                self.emit(f"mov x{i}, x{i + 1}")
            self.emit(f"b {handler.symbol}")
            self.label(skip)
        self.emit("brk #0x53")          # no message carries a handler number the actor lacks

    def file_label(self, path):
        path = path or "<input>"
        if path not in self.files:
            self.files[path] = f".Lfile_{len(self.files)}"
        return self.files[path]

    def string(self, data):
        """Put the address of a `Bytes` value holding `data` in x0."""
        if data not in self.strings:
            self.strings[data] = f".Lbytes_{len(self.strings)}"
        label = self.strings[data]
        self.emit(f"adrp x0, {label}")
        self.emit(f"add x0, x0, :lo12:{label}")

    def call_panic(self, line):
        """x0, x1 hold the message's address and length; never returns."""
        path = self.fn.file or "<input>"
        self.emit(f"adr x2, {self.file_label(path)}")
        self.emit(f"mov x3, #{len(os.path.basename(path))}")
        self.emit(f"ldr x4, ={line}")
        self.emit("bl rook_panic")

    def function(self, fn):
        self.fn = fn
        self.ret_label = self.new_label(f"ret_{fn.name}")
        self.panics = []        # (label, kind, line)
        self.loops = {}         # loop label -> (continue_label, break_label, depth)
        self.depth = 0          # temporaries currently pushed

        self.lines.append("")
        kind = f"method {fn.owner}.{fn.name}" if fn.owner else f"fn {fn.name}"
        self.lines.append(f"// {kind} (line {fn.pos.line})")
        self.emit(f".global {fn.symbol}")
        self.emit(".balign 4")
        self.label(fn.symbol)
        self.emit("stp x29, x30, [sp, #-16]!")
        self.emit("mov x29, sp")
        frame = (8 * fn.nslots + 15) // 16 * 16
        if frame:
            if frame <= 4095:
                self.emit(f"sub sp, sp, #{frame}")
            else:
                self.emit(f"ldr x16, ={frame}")
                self.emit("sub sp, sp, x16")
        if fn.result_slot is not None:
            # Where to write the struct result. Stored straight from x8: x0
            # still holds the first argument.
            self.emit(f"str x8, {self.slot_operand(fn.result_slot)}")
        first = 0
        if fn.self_slot is not None:
            self.store_slot(fn.self_slot)       # x0: the method's struct
            first = 1
        # Parameters: normalise numbers (the caller may be assembly) and store.
        for i, param in enumerate(fn.params):
            self.emit(f"mov x0, x{first + i}")
            if not (param.type.mut or is_aggregate(param.ty)):
                self.normalize(param.ty)
            self.store_slot(param.slot)

        self.block(fn.body)

        self.label(self.ret_label)
        self.emit("mov sp, x29")
        self.emit("ldp x29, x30, [sp], #16")
        self.emit("ret")

        for label, kind, line in self.panics:
            self.label(label)
            self.emit(f"adr x0, .Lmsg_{kind}")
            self.emit(f"mov x1, #{len(PANIC_MESSAGES[kind])}")
            self.call_panic(line)

    # ---- helpers -------------------------------------------------------

    def slot_operand(self, slot):
        offset = 8 * (slot + 1)
        if offset <= 256:
            return f"[x29, #-{offset}]"
        self.emit(f"ldr x17, ={offset}")
        self.emit("sub x17, x29, x17")
        return "[x17]"

    def load_slot(self, slot, reg="x0"):
        self.emit(f"ldr {reg}, {self.slot_operand(slot)}")

    def store_slot(self, slot):
        self.emit(f"str x0, {self.slot_operand(slot)}")

    def region_addr(self, slot, nwords, reg="x0"):
        """Address of the `nwords` slots starting at `slot` (the lowest address)."""
        offset = 8 * (slot + nwords)
        if offset <= 4095:
            self.emit(f"sub {reg}, x29, #{offset}")
        else:
            self.emit(f"ldr x17, ={offset}")
            self.emit(f"sub {reg}, x29, x17")

    def copy_words(self, n, src="x0", dst="x1"):
        """Copy an `n`-word struct from [src] to [dst]."""
        for i in range(n):
            self.emit(f"ldr x16, [{src}, #{8 * i}]")
            self.emit(f"str x16, [{dst}, #{8 * i}]")

    def push(self):
        self.emit("str x0, [sp, #-16]!")
        self.depth += 1

    def pop(self, reg):
        self.emit(f"ldr {reg}, [sp], #16")
        self.depth -= 1

    def leave_to(self, label):
        """Jump out to a loop label, popping temporaries pushed since the loop began."""
        target, depth = self.loops[label][:2], self.loops[label][2]
        if self.depth > depth:
            self.emit(f"add sp, sp, #{16 * (self.depth - depth)}")
        return target

    def load_imm(self, value, reg="x0"):
        value &= MASK64
        if value < 65536:
            self.emit(f"mov {reg}, #{value}")
        else:
            self.emit(f"ldr {reg}, ={value:#x}")

    def panic_branch(self, cond, kind, pos):
        """Emit a branch to a new panic stub. `cond` is e.g. "b.cs", "cbnz x16"."""
        label = self.new_label(f"panic_{kind}")
        self.panics.append((label, kind, pos.line))
        self.emit(f"{cond}, {label}" if cond.startswith("cb") else f"{cond} {label}")

    def normalize(self, ty):
        """Bring x0 into normal form for `ty` (used after casts and calls)."""
        if ty == BOOL:
            self.emit("tst w0, #0xff")
            self.emit("cset x0, ne")
        elif is_int(ty) and ty.bits < 64:
            if ty.signed:
                self.emit(f"{SIGN_EXTEND[ty.bits]} x0, w0")
            elif ty.bits == 32:
                self.emit("mov w0, w0")
            else:
                self.emit(f"and x0, x0, #{(1 << ty.bits) - 1:#x}")

    def check_fits(self, ty, pos):
        """x0 holds an exact result (no 64-bit overflow happened); panic if it
        doesn't fit in `ty` (bits < 64)."""
        if ty.signed:
            self.emit(f"{SIGN_EXTEND[ty.bits]} x16, w0")
            self.emit("cmp x16, x0")
            self.panic_branch("b.ne", "overflow", pos)
        else:
            self.emit(f"lsr x16, x0, #{ty.bits}")
            self.panic_branch("cbnz x16", "overflow", pos)

    # ---- statements ----------------------------------------------------

    def block(self, block):
        for stmt in block.stmts:
            self.stmt(stmt)

    def stmt(self, s):
        self.lines.append(f"    // line {s.pos.line}")
        if isinstance(s, S.Decl):
            self.expr(s.init)
            if is_aggregate(s.init.ty):
                self.region_addr(s.slot, s.init.ty.words, "x1")
                self.copy_words(s.init.ty.words)
            else:
                self.store_slot(s.slot)
        elif isinstance(s, S.Assign):
            target = s.target
            if isinstance(target, S.Name) and target.local.kind == "value":
                self.expr(s.value)
                self.store_slot(target.slot)
            else:
                self.expr(s.value)
                self.push()
                self.addr(target)
                self.emit("mov x1, x0")
                self.pop("x0")
                if is_aggregate(target.ty):
                    self.copy_words(target.ty.words)
                else:
                    self.emit("str x0, [x1]")
        elif isinstance(s, S.ExprStmt):
            self.expr(s.expr)
        elif isinstance(s, S.If):
            else_label = self.new_label("else")
            end_label = self.new_label("endif")
            self.expr(s.cond)
            self.emit(f"cbz x0, {else_label}")
            self.block(s.then)
            self.emit(f"b {end_label}")
            self.label(else_label)
            if isinstance(s.else_, S.If):
                self.stmt(s.else_)
            elif isinstance(s.else_, S.Block):
                self.block(s.else_)
            self.label(end_label)
        elif isinstance(s, S.Loop):
            start = self.new_label("loop")
            end = self.new_label("endloop")
            self.label(start)
            if s.cond is not None:
                self.expr(s.cond)
                self.emit(f"cbz x0, {end}")
            self.loops[s.label] = (start, end, self.depth)
            self.block(s.body)
            del self.loops[s.label]
            self.emit(f"b {start}")
            self.label(end)
        elif isinstance(s, S.ForRange):
            # The end is evaluated once. The variable can't overflow when
            # incremented, because it is always below the end.
            cond = self.new_label("range")
            step = self.new_label("rangestep")
            end = self.new_label("endrange")
            self.expr(s.start)
            self.store_slot(s.slot)
            self.expr(s.end)
            self.store_slot(s.end_slot)
            self.label(cond)
            self.load_slot(s.slot)
            self.load_slot(s.end_slot, "x1")
            self.emit("cmp x0, x1")
            self.emit(f"{'b.ge' if s.ty.signed else 'b.hs'} {end}")
            self.loops[s.label] = (step, end, self.depth)
            self.block(s.body)
            del self.loops[s.label]
            self.label(step)
            self.load_slot(s.slot)
            self.emit("add x0, x0, #1")
            self.store_slot(s.slot)
            self.emit(f"b {cond}")
            self.label(end)
        elif isinstance(s, S.Break):
            self.emit(f"b {self.leave_to(s.label)[1]}")
        elif isinstance(s, S.Continue):
            self.emit(f"b {self.leave_to(s.label)[0]}")
        elif isinstance(s, S.Match):
            self.match(s)
        elif isinstance(s, S.Unsafe):
            self.block(s.body)
        elif isinstance(s, S.Return):
            if s.value is not None:
                self.expr(s.value)
                if is_aggregate(s.value.ty):
                    self.load_slot(self.fn.result_slot, "x1")
                    self.copy_words(s.value.ty.words)
            self.emit(f"b {self.ret_label}")
        else:
            raise AssertionError(f"unknown statement {s!r}")

    # ---- expressions ---------------------------------------------------

    def expr(self, e):
        if isinstance(e, S.IntLit):
            self.load_imm(e.value)
        elif isinstance(e, S.BoolLit):
            self.emit(f"mov x0, #{int(e.value)}")
        elif isinstance(e, S.StrLit):
            self.string(e.data)
        elif isinstance(e, S.Name):
            if e.variant is not None:
                self.variant_value(e.temp, e.ty, e.variant)
                self.region_addr(e.temp, e.ty.words)
            elif e.const_str is not None:
                self.string(e.const_str.data)
            elif e.const_value is not None:
                self.load_imm(e.const_value)
            elif e.local.kind == "value":
                self.load_slot(e.slot)
            else:
                self.addr(e)                    # a struct: its address
                if not is_aggregate(e.ty):
                    self.emit("ldr x0, [x0]")   # a `mut` number parameter
        elif isinstance(e, S.FieldAccess):
            self.addr(e)
            if not is_aggregate(e.ty):
                self.emit("ldr x0, [x0]")
        elif isinstance(e, S.StructLit):
            self.struct_lit(e)
        elif isinstance(e, S.MethodCall):
            self.method_call(e)
        elif isinstance(e, S.Copy):
            self.addr(e.value)
            self.region_addr(e.temp, e.ty.words, "x1")
            self.copy_words(e.ty.words)
            self.region_addr(e.temp, e.ty.words)
        elif isinstance(e, S.Unary):
            self.unary(e)
        elif isinstance(e, S.Binary):
            self.binary(e)
        elif isinstance(e, S.Cast):
            self.expr(e.expr)
            self.normalize(e.ty)
        elif isinstance(e, S.IfExpr):
            else_label = self.new_label("ifelse")
            end_label = self.new_label("ifend")
            self.expr(e.cond)
            self.emit(f"cbz x0, {else_label}")
            self.expr(e.then)
            self.emit(f"b {end_label}")
            self.label(else_label)
            self.expr(e.else_)
            self.label(end_label)
        elif isinstance(e, S.Call) and e.callee in LOAD_INSNS:
            self.expr(e.args[0])
            self.emit(f"{LOAD_INSNS[e.callee]}, [x0]")         # exactly one access
        elif isinstance(e, S.Call) and e.callee in STORE_INSNS:
            self.expr(e.args[0])
            self.push()
            self.expr(e.args[1])
            self.emit("mov x1, x0")
            self.pop("x0")
            self.emit(f"{STORE_INSNS[e.callee]}, [x0]")
        elif isinstance(e, S.Call) and e.callee == "panic":
            self.expr(e.args[0])                                # a Bytes value's address
            self.emit("ldr x1, [x0, #8]")
            self.emit("ldr x0, [x0]")
            self.call_panic(e.pos.line)
        elif isinstance(e, S.Call):
            self.call(e.callee, None, e.args, e.ty, e.temp)
        elif isinstance(e, S.SelfValue):
            self.load_slot(self.fn.self_slot)
        elif isinstance(e, S.SelfRef):
            self.load_slot(self.fn.self_slot)       # the actor's reference is its fields' address
        elif isinstance(e, S.Narrow):
            self.expr(e.value)                      # the same reference
        elif isinstance(e, S.Spawn):
            self.spawn(e)
        elif isinstance(e, S.MatchExpr):
            self.match(e)
        else:
            raise AssertionError(f"unknown expression {e!r}")

    # ---- match ---------------------------------------------------------

    def match(self, m):
        """A match statement or value. The subject's value (or, for an enum,
        its address) is kept in a slot while the arms run."""
        ty = m.subject.ty
        end = self.new_label("matchend")
        labels = [self.new_label("arm") for _ in m.arms]
        self.expr(m.subject)
        self.store_slot(m.subject_slot)
        else_label = None
        if is_enum(ty):
            self.emit("ldr x16, [x0]")                  # the tag
            for arm, label in zip(m.arms, labels):
                for p in arm.patterns:
                    self.emit(f"cmp x16, #{p.variant.tag}")
                    self.emit(f"b.eq {label}")
        else:
            signed = is_int(ty) and ty.signed
            below = "b.lt" if signed else "b.lo"
            for arm, label in zip(m.arms, labels):
                if arm.patterns is None:
                    else_label = label
                    continue
                for p in arm.patterns:
                    self.load_imm(p.lo, "x1")
                    self.emit("cmp x0, x1")
                    if p.hi == p.lo + 1:
                        self.emit(f"b.eq {label}")
                        continue
                    # A range: lo <= x0 < hi. (hi is a value of the type, so
                    # it can always be loaded and compared.)
                    outside = self.new_label("outside")
                    self.emit(f"{below} {outside}")
                    self.load_imm(p.hi, "x1")
                    self.emit("cmp x0, x1")
                    self.emit(f"{below} {label}")
                    self.label(outside)
        if else_label is not None:
            self.emit(f"b {else_label}")
        else:
            # The checker proved every value is matched, so this is never reached.
            self.emit("brk #0x52")
        for arm, label in zip(m.arms, labels):
            self.label(label)
            for p in arm.patterns or []:
                for slot, offset, agg in p.slots:
                    self.load_slot(m.subject_slot)
                    if agg:
                        self.emit(f"add x0, x0, #{8 * offset}")     # lent: its address
                    else:
                        self.emit(f"ldr x0, [x0, #{8 * offset}]")
                    self.store_slot(slot)
            if isinstance(arm.body, S.Block):
                self.block(arm.body)
            elif isinstance(arm.body, S.Stmt):
                self.stmt(arm.body)
            else:
                self.expr(arm.body)
            self.emit(f"b {end}")
        self.label(end)

    def variant_value(self, temp, ty, variant):
        """Write `variant`'s tag into the enum value at `temp`, and zero the
        words its fields don't use."""
        used = 1 + sum(words(fty) for _, fty in variant.fields)
        self.region_addr(temp, ty.words, "x1")
        self.emit(f"mov x16, #{variant.tag}")
        self.emit("str x16, [x1]")
        for i in range(used, ty.words):
            self.emit(f"str xzr, [x1, #{8 * i}]")

    # ---- structs -------------------------------------------------------

    def addr(self, e):
        """Put the address of a place (or of a struct value) in x0."""
        if isinstance(e, S.Name) and (e.const_str is not None or e.variant is not None):
            self.expr(e)                            # a constant or variant: a new value
        elif isinstance(e, S.Name):
            local = e.local
            if local.kind == "region":
                self.region_addr(local.slot, local.ty.words)
            elif local.kind == "ref":
                self.load_slot(local.slot)
            else:
                self.region_addr(local.slot, 1)     # a number lent as `mut`
        elif isinstance(e, S.SelfValue):
            self.load_slot(self.fn.self_slot)
        elif isinstance(e, S.FieldAccess):
            if e.obj is None:
                self.load_slot(self.fn.self_slot)
            else:
                self.addr(e.obj)
            offset, _ = e.struct.offset(e.field)
            if offset:
                self.emit(f"add x0, x0, #{8 * offset}")
        else:
            self.expr(e)                            # a fresh struct: already an address

    def struct_lit(self, e):
        st = e.ty
        owner = e.variant if e.variant is not None else st
        for (name, value, _), (_, fty) in zip(e.fields, owner.fields):
            offset, _ = owner.offset(name)
            self.expr(value)
            self.region_addr(e.temp, st.words, "x1")
            if offset:
                self.emit(f"add x1, x1, #{8 * offset}")
            if is_aggregate(fty):
                self.copy_words(fty.words)
            else:
                self.emit("str x0, [x1]")
        if e.variant is not None:
            self.variant_value(e.temp, st, e.variant)
        self.region_addr(e.temp, st.words)

    def method_call(self, e):
        if e.send:
            self.send(e)
            return
        self.call(e.sig.decl.symbol, e.obj if e.obj is not None else "self",
                  e.args, e.ty, e.temp)

    def spawn(self, e):
        """Raven makes room for the actor (`raven_spawn_actor(fields, dispatcher)`
        gives its reference), then `new` runs on it. The reference is the value."""
        self.emit(f"mov x0, #{e.actor.words}")
        self.emit(f"adr x1, {e.actor.name}__dispatch")
        self.emit("bl raven_spawn_actor")
        self.store_slot(e.temp)
        if e.sig is not None:
            for arg in e.args:
                self.expr(arg)
                self.push()
            for i in reversed(range(len(e.args))):
                self.pop(f"x{i + 1}")
            self.load_slot(e.temp)                  # x0: the new actor, `new`'s self
            self.emit(f"bl {e.actor.name}__new")
        self.load_slot(e.temp)

    def send(self, e):
        """`raven_send(target, handler number, a0, a1, a2, a3)`: Raven puts the
        message in the target's mailbox, or drops it if the mailbox is full. A
        `reliable` handler calls `raven_send_reliable` instead, which writes
        a `Sent` to the address in x8 rather than dropping."""
        self.expr(e.obj)
        self.push()
        for arg in e.args:
            self.expr(arg)
            self.push()
        n = 1 + len(e.args)
        for i in reversed(range(n)):
            self.pop("x0" if i == 0 else f"x{i + 1}")
        self.emit(f"mov x1, #{e.handler_index}")
        for i in range(len(e.args), 4):
            self.emit(f"mov x{i + 2}, #0")
        if e.sig.decl.handler == "reliable":
            self.region_addr(e.temp, e.ty.words, "x8")
            self.emit("bl raven_send_reliable")
            self.region_addr(e.temp, e.ty.words)
        else:
            self.emit("bl raven_send")

    def call(self, symbol, receiver, args, ret, temp):
        """Call a function or method. Struct arguments are passed by address."""
        n = 0
        if receiver is not None:
            if receiver == "self":
                self.load_slot(self.fn.self_slot)
            else:
                self.addr(receiver)
            self.push()
            n = 1
        for arg in args:
            if isinstance(arg, S.MutArg):
                self.addr(arg.place)
            else:
                self.expr(arg)                      # a struct gives its address
            self.push()
            n += 1
        for i in reversed(range(n)):
            self.pop(f"x{i}")
        if is_aggregate(ret):
            self.region_addr(temp, ret.words, "x8")
        self.emit(f"bl {symbol}")
        if is_aggregate(ret):
            self.region_addr(temp, ret.words)
        elif ret != UNIT:
            self.normalize(ret)

    def unary(self, e):
        self.expr(e.operand)
        ty = e.ty
        if e.op == "-":
            if ty.bits == 64:
                self.emit("negs x0, x0")
                self.panic_branch("b.vs", "overflow", e.pos)
            else:
                self.emit("neg x0, x0")
                self.check_fits(ty, e.pos)
        elif ty == BOOL:
            self.emit("eor x0, x0, #1")
        else:
            self.emit("mvn x0, x0")
            self.normalize(ty)

    def binary(self, e):
        op = e.op
        if op in ("and", "or") and e.ty == BOOL:
            # Logical, short-circuit: x0 is already the answer if the left
            # side decides it.
            end = self.new_label("logic")
            self.expr(e.left)
            self.emit(f"{'cbz' if op == 'and' else 'cbnz'} x0, {end}")
            self.expr(e.right)
            self.label(end)
            return

        self.expr(e.left)
        self.push()
        self.expr(e.right)
        self.emit("mov x1, x0")
        self.pop("x0")
        operand = e.left.ty

        if op in EQ_COND or op in SIGNED_COND:
            if op in EQ_COND:
                cond = EQ_COND[op]
            else:
                cond = (SIGNED_COND if operand.signed else UNSIGNED_COND)[op]
            self.emit("cmp x0, x1")
            self.emit(f"cset x0, {cond}")
            return

        ty = e.ty
        if op == "+":
            self.add_sub("adds" if ty.bits == 64 else "add", ty, e)
        elif op == "-":
            if not ty.signed:
                self.emit("subs x0, x0, x1")
                self.panic_branch("b.lo", "overflow", e.pos)
            else:
                self.add_sub("subs" if ty.bits == 64 else "sub", ty, e)
        elif op == "*":
            if ty.bits == 64:
                self.emit(f"{'smulh' if ty.signed else 'umulh'} x16, x0, x1")
                self.emit("mul x0, x0, x1")
                if ty.signed:
                    self.emit("cmp x16, x0, asr #63")
                    self.panic_branch("b.ne", "overflow", e.pos)
                else:
                    self.panic_branch("cbnz x16", "overflow", e.pos)
            else:
                self.emit("mul x0, x0, x1")     # exact: both fit in 32 bits
                self.check_fits(ty, e.pos)
        elif op in ("/", "%"):
            self.panic_branch("cbz x1", "div0", e.pos)
            div = "sdiv" if ty.signed else "udiv"
            if op == "/":
                if ty.signed and ty.bits == 64:
                    # MIN / -1 overflows; the hardware wouldn't trap.
                    ok = self.new_label("divok")
                    self.emit("cmn x1, #1")
                    self.emit(f"b.ne {ok}")
                    self.emit("mov x16, #0x8000000000000000")
                    self.emit("cmp x0, x16")
                    self.panic_branch("b.eq", "overflow", e.pos)
                    self.label(ok)
                self.emit(f"{div} x0, x0, x1")
                if ty.signed and ty.bits < 64:
                    self.check_fits(ty, e.pos)
            else:
                self.emit(f"{div} x16, x0, x1")
                self.emit("msub x0, x16, x1, x0")
        elif op in ("and", "or", "xor"):
            # Bitwise on integers (and `xor` on bools): normal form is kept.
            insn = {"and": "and", "or": "orr", "xor": "eor"}[op]
            self.emit(f"{insn} x0, x0, x1")
        elif op in ("shl", "shr"):
            # Negative amounts are huge when compared unsigned, so this
            # catches them too.
            self.emit(f"cmp x1, #{ty.bits}")
            self.panic_branch("b.hs", "shift", e.pos)
            if op == "shl":
                # Panic if set bits are lost: shifting back must give the
                # original value (arithmetically, for signed types).
                self.emit("mov x17, x0")
                self.emit("lsl x0, x0, x1")
                self.normalize(ty)
                self.emit(f"{'asr' if ty.signed else 'lsr'} x16, x0, x1")
                self.emit("cmp x16, x17")
                self.panic_branch("b.ne", "shiftlost", e.pos)
            else:
                self.emit(f"{'asr' if ty.signed else 'lsr'} x0, x0, x1")
        else:
            raise AssertionError(f"unknown operator {op}")

    def add_sub(self, insn, ty, e):
        self.emit(f"{insn} x0, x0, x1")
        if ty.bits == 64:
            # adds: unsigned overflow sets carry; signed sets V.
            self.panic_branch("b.vs" if ty.signed else "b.cs", "overflow", e.pos)
        else:
            self.check_fits(ty, e.pos)

